#!/usr/bin/env node
/**
 * Copies the skills this server publishes over MCP (Skills extension,
 * SEP-2640) from the repository's skills/ directory into
 * src/modules/skills-catalog.generated.ts, with each file's sha256 digest and
 * size, and its SKILL.md frontmatter as JSON.
 *
 * Generated rather than read at runtime: the package ships without the
 * repository's skills/ directory, and an inlined catalog works wherever the
 * server runs. test/skills.test.ts fails when the catalog drifts from the
 * source, so run `pnpm sync:skills` after editing a published skill.
 *
 * Usage: node scripts/sync-skills.mjs
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

/** Skills about investigating live telemetry: what an agent connected to this server needs. */
export const PUBLISHED = [
  'integrations/autotel-mcp',
  'core/analyze-traces',
  'core/debug-missing-spans',
];

const here = dirname(fileURLToPath(import.meta.url));
const skillsRoot = join(here, '../../../skills');
const output = join(here, '../src/modules/skills-catalog.generated.ts');

function filesOf(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? filesOf(join(dir, entry.name))
        : [join(dir, entry.name)],
    )
    .toSorted();
}

function frontmatterOf(text, path) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!match) throw new Error(`${path}: SKILL.md has no frontmatter`);
  return parse(match[1]);
}

export function buildCatalog() {
  return PUBLISHED.map((source) => {
    const dir = join(skillsRoot, source);
    const files = filesOf(dir).map((file) => {
      const bytes = readFileSync(file);
      return {
        path: relative(dir, file).split('\\').join('/'),
        text: bytes.toString('utf8'),
        digest: `sha256:${createHash('sha256').update(bytes).digest('hex')}`,
        size: bytes.length,
      };
    });
    const skillMd = files.find((file) => file.path === 'SKILL.md');
    if (!skillMd) throw new Error(`${source}: no SKILL.md`);
    const frontmatter = frontmatterOf(skillMd.text, source);
    // The skill path's final segment must be the skill's name (SEP-2640).
    if (frontmatter.name !== source.split('/').at(-1)) {
      throw new Error(
        `${source}: frontmatter name "${frontmatter.name}" does not match its directory`,
      );
    }
    return { name: frontmatter.name, frontmatter, files };
  });
}

export function renderCatalog(catalog) {
  return `// Generated by scripts/sync-skills.mjs from the repository's skills/ directory.
// Do not edit: change the skill there and run \`pnpm sync:skills\`.
/* oxlint-disable unicorn/numeric-separators-style -- generated byte sizes */
import type { PublishedSkill } from './skills';

export const SKILL_CATALOG: readonly PublishedSkill[] = ${JSON.stringify(catalog, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(output, renderCatalog(buildCatalog()));
  console.log(`wrote ${relative(process.cwd(), output)}`);
}
